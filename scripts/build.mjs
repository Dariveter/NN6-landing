import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { root, site, dist } from './paths.mjs';

const check = spawnSync(process.execPath, [path.join(root,'scripts/check.mjs')], {cwd:root,stdio:'inherit'});
if (check.status !== 0) process.exit(check.status || 1);
const marker = path.join(dist,'.field-generated');
if (fs.existsSync(dist)) {
  assert(fs.existsSync(marker),'dist already exists without a build marker; move your own files before building');
  // Only replace this script's marked, generated output.
  fs.rmSync(dist,{recursive:true,force:true});
}
fs.mkdirSync(dist,{recursive:true});
fs.writeFileSync(marker,'Generated by scripts/build.mjs. Edit site/, not dist/.\n');
const copy = (from,to) => {
  for (const entry of fs.readdirSync(from,{withFileTypes:true})) {
    if (entry.name === 'api' || entry.name.startsWith('.')) continue;
    const source=path.join(from,entry.name),target=path.join(to,entry.name);
    assert(!entry.isSymbolicLink(),'Symbolic links are not published');
    if(entry.isDirectory()){fs.mkdirSync(target,{recursive:true});copy(source,target);}
    else fs.copyFileSync(source,target);
  }
};
copy(site,dist);
console.log('Static publication directory: dist/');
console.log('Optional Vercel handler: api/neuroniy.js (paid AI stays disabled by default).');
